// frontend/src/pages/auth/register.jsx
import React, { useState } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import axios from 'axios'; // 👈 1. Swapped out Supabase for Axios

// Same rule enforced on the backend — this is just for instant UX feedback.
const PASSWORD_REGEX = /^(?=.*[A-Za-z])(?=.*\d)(?=.*[^A-Za-z\d]).{8,}$/;

function getPasswordChecks(password) {
  return {
    length: password.length >= 8,
    letter: /[A-Za-z]/.test(password),
    number: /\d/.test(password),
    special: /[^A-Za-z\d]/.test(password),
  };
}

function Register() {
  const navigate = useNavigate();
  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [error, setError] = useState(null);
  const [loading, setLoading] = useState(false);
  const [touchedPassword, setTouchedPassword] = useState(false);

  const passwordChecks = getPasswordChecks(password);
  const isPasswordStrong = PASSWORD_REGEX.test(password);

  // 2. Custom Registration Handler connecting to your local Express server
  const handleSubmit = async (e) => {
    e.preventDefault();
    setError(null);

    if (!isPasswordStrong) {
      setTouchedPassword(true);
      setError('Please choose a stronger password before continuing.');
      return;
    }

    setLoading(true);

    try {
      // 👈 3. Make a direct network request to your custom backend API
      const response = await axios.post('http://localhost:5000/api/auth/register', {
        name,
        email,
        password
      });

      // Show success message from server and route to login
      alert(response.data.message || 'Registration successful! Please check your email to verify your account.');
      navigate('/login');
    } catch (err) {
      console.error("Registration failure:", err);
      // Grab error messages generated by your backend routes
      setError(err.response?.data?.message || "Could not complete signup. Try again later.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="min-h-screen bg-gray-50 flex flex-col justify-center py-12 sm:px-6 lg:px-8">
      <div className="sm:mx-auto w-full max-w-md">
        <h2 className="text-center text-3xl font-extrabold text-gray-900">Create your account</h2>
        <p className="mt-2 text-center text-sm text-gray-600">
          Already have an account?{' '}
          <Link to="/login" className="font-medium text-blue-600 hover:text-blue-500">
            Sign in
          </Link>
        </p>
      </div>

      <div className="mt-8 sm:mx-auto w-full max-w-md">
        <div className="bg-white py-8 px-4 shadow sm:rounded-lg sm:px-10 border border-gray-100">

          {/* DYNAMIC ERROR BADGE */}
          {error && (
            <div className="mb-4 p-3 bg-red-50 border border-red-200 text-red-600 text-sm font-semibold rounded-md text-center">
              ⚠️ {error}
            </div>
          )}

          <form className="space-y-6" onSubmit={handleSubmit}>
            <div>
              <label className="block text-sm font-medium text-gray-700">Full Name</label>
              <input
                type="text"
                required
                value={name}
                onChange={(e) => setName(e.target.value)}
                disabled={loading}
                className="mt-1 block w-full px-3 py-2 border border-gray-300 rounded-md shadow-sm focus:outline-none focus:ring-blue-500 focus:border-blue-500 sm:text-sm"
              />
            </div>

            <div>
              <label className="block text-sm font-medium text-gray-700">Email address</label>
              <input
                type="email"
                required
                value={email}
                onChange={(e) => setEmail(e.target.value)}
                disabled={loading}
                className="mt-1 block w-full px-3 py-2 border border-gray-300 rounded-md shadow-sm focus:outline-none focus:ring-blue-500 focus:border-blue-500 sm:text-sm"
              />
              <p className="mt-1 text-xs text-gray-400">
                We'll send a verification link here — make sure it's a real inbox you can check.
              </p>
            </div>

            <div>
              <label className="block text-sm font-medium text-gray-700">Password</label>
              <input
                type="password"
                required
                value={password}
                onChange={(e) => setPassword(e.target.value)}
                onBlur={() => setTouchedPassword(true)}
                disabled={loading}
                className="mt-1 block w-full px-3 py-2 border border-gray-300 rounded-md shadow-sm focus:outline-none focus:ring-blue-500 focus:border-blue-500 sm:text-sm"
              />

              {/* PASSWORD STRENGTH CHECKLIST */}
              {(touchedPassword || password.length > 0) && (
                <ul className="mt-2 space-y-1 text-xs">
                  <li className={passwordChecks.length ? 'text-green-600' : 'text-gray-400'}>
                    {passwordChecks.length ? '✓' : '○'} At least 8 characters
                  </li>
                  <li className={passwordChecks.letter ? 'text-green-600' : 'text-gray-400'}>
                    {passwordChecks.letter ? '✓' : '○'} Contains a letter
                  </li>
                  <li className={passwordChecks.number ? 'text-green-600' : 'text-gray-400'}>
                    {passwordChecks.number ? '✓' : '○'} Contains a number
                  </li>
                  <li className={passwordChecks.special ? 'text-green-600' : 'text-gray-400'}>
                    {passwordChecks.special ? '✓' : '○'} Contains a special character (!@#$%...)
                  </li>
                </ul>
              )}
            </div>

            <div>
              <button
                type="submit"
                disabled={loading}
                className="w-full flex justify-center py-2 px-4 border border-transparent rounded-md shadow-sm text-sm font-medium text-white bg-blue-600 hover:bg-blue-700 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-blue-500 transition disabled:bg-blue-300"
              >
                {loading ? 'Creating Account...' : 'Register Account'}
              </button>
            </div>
          </form>
        </div>
      </div>
    </div>
  );
}

export default Register;
